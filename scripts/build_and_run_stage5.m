    'function d = Discrete_PID_Controller(e, w_ref, a_ref, ff_mode)\n' ...
    '%% Corrected Discrete PID Controller (Ts = 1 ms) - Validated Optimization\n' ...
    '%% Kp=0.50, Ki=8.00, Kd=0.0000, N=20 with Conditional Anti-Windup Clamping\n' ...
    'if ff_mode == 0 %% Phase 1 Unassisted Baseline Failed Configuration\n' ...
    '    Kp = 2.50;\n' ...
    '    Ki = 0.50;\n' ...
    '    Kd = 0.080;\n' ...
    '    N  = 100;\n' ...
    '    Kff_v = 0.0;\n' ...
    '    Kff_a = 0.0;\n' ...
    'else %% Phase 2 Corrected & Validated Optimized Feedforward Configuration\n' ...
    '    Kp = 0.50;\n' ...
    '    Ki = 8.00;\n' ...
    '    Kd = 0.0000;\n' ...
    '    N  = 20;\n' ...
    '    Kff_v = 0.004175;             %% (Ke + R*B/Kt) / V_dc\n' ...
    '    Kff_a = 0.00000834;           %% (J*R/Kt + L*B/Kt) / V_dc\n' ...
    'end\n' ...
    'Ts = 0.001;\n' ...
    '\n' ...
    'persistent u_i u_d e_prev\n' ...
    'if isempty(u_i)\n' ...
