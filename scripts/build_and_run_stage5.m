    'w_max = 8.0;  %% rad/s\n' ...
    'step_rad = 90.0 * pi / 180; %% 1.5707963 rad\n' ...
    't_a = w_max / a_max; %% 0.160 s\n' ...
    'theta_a = 0.5 * a_max * t_a^2; %% 0.640 rad\n' ...
