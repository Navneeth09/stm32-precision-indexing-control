    '    u_ff = 0.0;\n' ...
    'end\n' ...
    '\n' ...
    '%% 5. Total Tentative Control Output u_calc\n' ...
    'u_calc = u_p + v_i + u_d + u_ff;\n' ...
    '\n' ...
    '%% 6. Actuator Duty Cycle Saturation [0.0, 1.0]\n' ...
    'if u_calc > 1.0\n' ...
    '    d = 1.0;\n' ...
    'elseif u_calc < 0.0\n' ...
    '    d = 0.0;\n' ...
    'else\n' ...
    '    d = u_calc;\n' ...
    'end\n' ...
    '\n' ...
    '%% 7. Conditional Integration Anti-Windup Clamping\n' ...
    'is_sat_high = (u_calc > 1.0) && (e > 0);\n' ...
    'is_sat_low  = (u_calc < 0.0) && (e < 0);\n' ...
    'if is_sat_high || is_sat_low\n' ...
    '    u_i = u_i;\n' ...
    'else\n' ...
    '    u_i = v_i;\n' ...
    'end\n' ...
    '\n' ...
    'e_prev = e;\n' ...
    'end\n']);

