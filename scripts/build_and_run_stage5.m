    'u_d = (Kd * N * (e - e_prev) + u_d) / (1.0 + N * Ts);\n' ...
    '\n' ...
    '%% 3. Tentative Discrete Integrator Update\n' ...
    'v_i = u_i + Ki * Ts * e;\n' ...
    '\n' ...
    '%% 4. Explicit Configurable Feedforward Term\n' ...
    'if ff_mode == 1\n' ...
